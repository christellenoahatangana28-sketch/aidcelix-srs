export function fill(template: string, vars: Record<string, string | number> = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function lookup(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const value = messages[locale][key];
  return vars ? fill(value, vars) : value;
}

export function translateCategory(locale: Locale, category: string) {
  const key = CATEGORY_KEYS[category];
  return key ? messages[locale][key] : category;
}

